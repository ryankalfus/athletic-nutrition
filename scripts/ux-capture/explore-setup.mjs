import { writeFileSync, mkdirSync } from "node:fs";
import { launch, newPage, BASE, dump, D, HERE } from "./lib.mjs";
mkdirSync(`${HERE}/seeds`, { recursive: true });
const browser = await launch();
const { page: p } = await newPage(browser, "desktop", { clock: D(2026, 10, 13, 7, 0) });
const next = () => p.getByRole("button", { name: "Next", exact: true }).click();
await p.goto(BASE);
await p.getByRole("button", { name: "Get started" }).click();
await p.getByRole("textbox", { name: /First name/ }).fill("Maya");
await p.getByRole("combobox", { name: /^Sport/ }).fill("Soccer");
await p.getByRole("radiogroup", { name: "Season" }).getByRole("radio", { name: "In season" }).click();
await next();
await p.getByRole("heading", { name: "Your school day", level: 1 }).waitFor();
console.log((await p.locator("main").innerText()).slice(0, 800));
await next();
await p.getByRole("heading", { name: "Practices and games", level: 1 }).waitFor();
const days = p.getByRole("group", { name: "Practice days" });
for (const d of ["Monday", "Tuesday", "Wednesday", "Thursday"]) await days.getByRole("button", { name: d }).click();
await p.getByRole("button", { name: /Add a game/ }).click();
console.log((await p.locator("main").innerText()).slice(0, 1200));
await p.getByLabel("Game date").fill("2026-10-17");
await next();
await p.getByRole("heading", { name: "Food at school", level: 1 }).waitFor();
console.log((await p.locator("main").innerText()).slice(0, 800));
await p.getByRole("group", { name: "At school I have" }).getByRole("button", { name: "Microwave" }).click();
await next();
await p.getByRole("heading", { name: "Food needs", level: 1 }).waitFor();
console.log((await p.locator("main").innerText()).slice(0, 1200));
await next();
await p.getByRole("heading", { name: "You're set", level: 1 }).waitFor();
console.log((await p.locator("main").innerText()).slice(0, 800));
await p.getByRole("button", { name: "Open Today" }).click();
await p.getByRole("heading", { name: "Today", exact: true }).waitFor();
await p.waitForTimeout(500);
console.log("=== TODAY\n", (await p.locator("body").innerText()).slice(0, 3000));
writeFileSync(`${HERE}/seeds/after-setup.json`, JSON.stringify(await dump(p), null, 1));
await browser.close();
